// Derives prisma/schema.sqlite.prisma from prisma/schema.prisma so local testing can use a single SQLite file.
// PostgreSQL stays the real database; this is for quick local runs only.
import fs from "fs";

let s = fs.readFileSync("prisma/schema.prisma", "utf8");
s = s.replace(/datasource db \{[\s\S]*?\}/, 'datasource db {\n  provider = "sqlite"\n  url      = env("DATABASE_URL")\n}');
s = s.replace(/ @db\.\w+(\([^)]*\))?/g, "");                         // @db.Date, @db.Decimal(14, 2)
s = s.replace(/(\w+)\s+String\[\]/g, '$1 Json @default("[]")');       // scalar lists are not supported
s = s.replace(/Int\s+@unique @default\(autoincrement\(\)\)/g, "Int @unique"); // receipt no. is assigned in code
fs.writeFileSync("prisma/schema.sqlite.prisma", "// GENERATED by scripts/make-sqlite-schema.mjs — do not edit\n" + s);
console.log("wrote prisma/schema.sqlite.prisma");
