/**
 * Builds a STATIC, browsable snapshot of the app for GitHub Pages (docs/demo).
 * It is a visual walkthrough with demo data: forms do not save anything.
 *
 * Usage (needs a running production server on a freshly seeded DB):
 *   BASE_URL=http://localhost:3002 npx tsx scripts/build-demo.ts docs/demo
 */
import fs from "fs";
import path from "path";
import { chromium, type APIRequestContext } from "playwright";

const BASE = process.env.BASE_URL ?? "http://localhost:3002";
const OUT = path.resolve(process.argv[2] ?? "docs/demo");
const LIMITS: [RegExp, number][] = [[/^\/pilgrims\/[0-9a-f-]{36}$/, 8], [/^\/bookings\//, 6], [/^\/agents\/[0-9a-f-]{36}$/, 3]];

const exe = fs.readdirSync("/opt/pw-browsers").filter((x) => x.startsWith("chromium-")).map((d) => `/opt/pw-browsers/${d}/chrome-linux64/chrome`).find((p) => fs.existsSync(p));

/** URL (path+query) -> output file (relative to OUT), or null if not a page we snapshot. */
function fileFor(url: string): string | null {
  const u = new URL(url, BASE);
  let p = u.pathname.replace(/\/$/, "") || "/dashboard";
  if (p === "/login") return "index.html";
  if (/\/rooming$/.test(p)) p += `-${u.searchParams.get("city") ?? "default"}`;
  if (p === "/trips/new" || p === "/pilgrims/new") p += "-form";
  return p.slice(1) + ".html";
}
const rel = (from: string, to: string) => {
  const r = path.posix.relative(path.posix.dirname(from), to);
  return r === "" ? path.posix.basename(to) : r;
};

(async () => {
  fs.rmSync(OUT, { recursive: true, force: true });
  fs.mkdirSync(path.join(OUT, "assets/fonts"), { recursive: true });
  fs.mkdirSync(path.join(OUT, "files"), { recursive: true });
  for (const f of fs.readdirSync("public/fonts").filter((f) => f.endsWith(".woff2"))) fs.copyFileSync(path.join("public/fonts", f), path.join(OUT, "assets/fonts", f));
  fs.writeFileSync(path.join(OUT, ".nojekyll"), "");

  const browser = await chromium.launch({ executablePath: exe, args: ["--no-sandbox"] });
  const ctx = await browser.newContext({ viewport: { width: 1280, height: 900 }, locale: "ar" });
  const page = await ctx.newPage();

  // 1) login page (index) then log in
  await page.goto(`${BASE}/login`);
  const loginHtml = await page.content();
  await page.fill("#username", "admin"); await page.fill("#password", process.env.DEMO_PASSWORD ?? "ChangeMe123");
  await page.click("button:has-text('دخول')"); await page.waitForURL("**/dashboard");

  const queue: string[] = ["/dashboard", "/pilgrims", "/trips", "/hotels", "/agents", "/import", "/users", "/audit", "/settings", "/programs", "/pilgrims/new", "/trips/new"];
  const seen = new Map<string, string>(); // file -> html
  const counts = new Map<RegExp, number>();
  const apiLinks = new Map<string, string>(); // api url -> saved file
  let css = "";

  const allowed = (p: string) => {
    for (const [re, max] of LIMITS) if (re.test(p)) { const n = counts.get(re) ?? 0; if (n >= max) return false; counts.set(re, n + 1); return true; }
    return true;
  };

  const done = new Set<string>();
  while (queue.length) {
    const url = queue.shift()!;
    const file = fileFor(url);
    if (!file || done.has(file)) continue;
    const pathname = new URL(url, BASE).pathname;
    if (!allowed(pathname)) continue;
    done.add(file);
    const resp = await page.goto(BASE + url, { waitUntil: "networkidle" });
    if (!resp || !resp.ok() || page.url().includes("/login") || page.url().includes("/forbidden")) { done.delete(file); continue; }
    if (!css) {
      const hrefs = await page.$$eval("link[rel=stylesheet]", (els) => els.map((e) => (e as HTMLLinkElement).href));
      for (const h of hrefs) css += (await (await page.request.get(h)).text()) + "\n";
      css = css.replace(/url\(\/?fonts\//g, "url(fonts/");
      fs.writeFileSync(path.join(OUT, "assets/app.css"), css);
    }
    seen.set(file, await page.content());
    const hrefs = await page.$$eval("a[href]", (els) => els.map((e) => (e as HTMLAnchorElement).getAttribute("href")!));
    for (const h of hrefs) {
      if (!h.startsWith("/")) continue;
      if (h.startsWith("/api/")) { apiLinks.set(h, ""); continue; }
      queue.push(h);
    }
  }

  // 2) sample outputs (PDF / Excel) generated by the real app
  const api: APIRequestContext = ctx.request;
  let n = 0;
  const byHash = new Map<string, string>();
  for (const h of apiLinks.keys()) {
    const r = await api.get(BASE + h);
    if (!r.ok()) continue;
    const ct = r.headers()["content-type"] ?? "";
    const ext = ct.includes("pdf") ? "pdf" : ct.includes("sheet") ? "xlsx" : "bin";
    const body = await r.body();
    // identical outputs reached through different links share one file
    const key = ext + ":" + body.length + ":" + body.subarray(0, 64).toString("base64");
    const ctype = h.match(/outputs\/([\w-]+)/)?.[1] ?? (h.includes("statement") ? "agent-statement" : "receipt");
    let name = byHash.get(key);
    if (!name) {
      name = `files/${String(++n).padStart(2, "0")}-${ctype}${h.match(/city=(\w+)/) ? "-" + h.match(/city=(\w+)/)![1].toLowerCase() : ""}.${ext}`;
      fs.writeFileSync(path.join(OUT, name), body);
      byHash.set(key, name);
    }
    apiLinks.set(h, name);
  }
  await browser.close();

  // 3) rewrite & write pages
  const BANNER = `<div dir="rtl" style="background:#fff3cd;color:#664d03;text-align:center;padding:6px 10px;font-size:13px;font-weight:700;border-bottom:1px solid #ffe69c">نسخة عرض ثابتة للتجربة البصرية — بيانات وهمية، والأزرار لا تحفظ شيئاً. التطبيق الحقيقي يعمل على سيرفر.</div>`;
  const SCRIPT = `<script>document.addEventListener("submit",function(e){e.preventDefault();if(document.querySelector("#username")){location.href=ROOT+"dashboard.html";return}alert("هذه نسخة عرض ثابتة: لا يتم حفظ البيانات.")});</script>`;
  const write = (file: string, html: string) => {
    const root = path.posix.relative(path.posix.dirname(file), ".") || ".";
    const prefix = root === "." ? "" : root + "/";
    let out = html
      .replace(/<script[\s\S]*?<\/script>/g, "")
      .replace(/<link[^>]+rel="(stylesheet|preload|prefetch)"[^>]*>/g, "")
      .replace(/<next-route-announcer[\s\S]*?<\/next-route-announcer>/g, "")
      .replace(/<form[^>]*action="javascript:throw[^"]*"/g, (m) => m)
      .replace(/href="([^"]*)"/g, (m, h: string) => {
        h = h.replace(/&amp;/g, "&");
        if (!h.startsWith("/")) return m;
        if (h.startsWith("/api/")) { const f = apiLinks.get(h); return f ? `href="${rel(file, f)}"` : `href="#"`; }
        const target = fileFor(h);
        return target && seen.has(target) ? `href="${rel(file, target)}"` : `href="#" title="غير متوفر في العرض الثابت"`;
      })
      .replace("</head>", `<link rel="stylesheet" href="${prefix}assets/app.css"></head>`)
      .replace(/<body([^>]*)>/, `<body$1>${BANNER}`)
      .replace("</body>", `<script>var ROOT=${JSON.stringify(prefix)};</script>${SCRIPT}</body>`);
    const dest = path.join(OUT, file);
    fs.mkdirSync(path.dirname(dest), { recursive: true });
    fs.writeFileSync(dest, out);
  };
  write("index.html", loginHtml);
  for (const [file, html] of seen) write(file, html);
  console.log(`pages: ${seen.size + 1}, files: ${n}, css: ${(css.length / 1024).toFixed(0)}KB`);
})();
